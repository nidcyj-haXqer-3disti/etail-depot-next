import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { guideImageSources } from './guide-image-sources.mjs';

// Reuse the Sharp version already pinned through Next.js; no hosted image runtime.
const require = createRequire(import.meta.url);
const sharp = createRequire(require.resolve('next/package.json'))('sharp');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const check = process.argv.includes('--check');
const receipts = [];
const digest = value => createHash('sha256').update(value).digest('hex');
function output(file, value) {
  const bytes = Buffer.isBuffer(value) ? value : Buffer.from(value);
  if (check) assert.deepEqual(readFileSync(file), bytes, `Regenerate ${path.relative(root, file)}`);
  else { mkdirSync(path.dirname(file), { recursive: true }); writeFileSync(file, bytes); }
}
for (const [group, entries] of Object.entries(guideImageSources)) {
  const assets = path.join(root, `src/features/resources/integrations/${group}/assets`);
  const generated = assets;
  mkdirSync(path.join(assets, "previews"), { recursive: true });
  const imports = new Map();
  function imageImport(file) {
    if (!imports.has(file)) imports.set(file, `image${imports.size}`);
    return imports.get(file);
  }
  const definitions = [];
  for (const [key, spec] of Object.entries(entries)) {
    const original = readFileSync(path.join(assets, spec.file));
    const metadata = await sharp(original).metadata();
    const frames = spec.frames ?? [null];
    const items = [];
    for (const [index, frame] of frames.entries()) {
      let bytes = original;
      let file = spec.file;
      const width = frame?.[2] ?? metadata.width;
      const height = frame?.[3] ?? metadata.height;
      const stem = `${path.parse(spec.file).name}-preview-${key.replace(/\W+/g, '-')}${frames.length > 1 ? `-${index + 1}` : ''}`;
      if (frame) {
        const [left, top] = frame;
        bytes = await sharp(original).extract({ left, top, width, height }).webp({ lossless: true, effort: 6 }).toBuffer();
        // Native-size previews must preserve every decoded source pixel, including redactions.
        const sourcePixels = await sharp(original).extract({ left, top, width, height }).removeAlpha().raw().toBuffer();
        assert.deepEqual(await sharp(bytes).removeAlpha().raw().toBuffer(), sourcePixels, `${key}: changed crop pixels`);
        file = `previews/${stem}.webp`;
        output(path.join(assets, file), bytes);
      }
      const variants = [];
      for (const target of [640, 1040]) {
        if (target >= width) continue;
        const resized = await sharp(bytes).resize({ width: target, withoutEnlargement: true }).webp({ lossless: true, effort: 6 }).toBuffer();
        // Do not offer a smaller image if its lossless encoding does not save useful bytes.
        if (resized.length >= bytes.length * 0.9) continue;
        const variantFile = `previews/${stem}-${target}.webp`;
        output(path.join(assets, variantFile), resized);
        variants.push(imageImport(variantFile));
        receipts.push({ group, key, source: spec.file, sourceSha256: digest(original), frame, width: target, file: variantFile, bytes: resized.length, sha256: digest(resized) });
      }
      const image = imageImport(file);
      variants.push(image);
      items.push(`{ image: ${image}, variants: [${variants.join(', ')}], frame: ${JSON.stringify(frame)} }`);
      receipts.push({ group, key, source: spec.file, sourceSha256: digest(original), frame, width, height, file, bytes: bytes.length, sha256: digest(bytes) });
    }
    definitions.push(`  ${JSON.stringify(key)}: [${items.join(', ')}],`);
  }
  output(path.join(generated, `${group}-preview-assets.ts`), `// Generated by tools/generate-guide-image-previews.mjs. Do not hand-edit.\n${[...imports].map(([file, name]) => `import ${name} from "./${file}";`).join('\n')}\n\nexport const ${group}PreviewAssets = {\n${definitions.join('\n')}\n} as const;\n`);
}
output(path.join(root, 'tools/guide-image-previews.json'), JSON.stringify({ schemaVersion: 1, sharp: sharp.versions.sharp, receipts }, null, 2) + '\n');
console.log(`${check ? 'Verified' : 'Generated'} ${receipts.length} guide preview entries; original images unchanged.`);
