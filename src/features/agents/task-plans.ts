/** New outcomes must receive their own source-backed plan rather than a generic fallback. */
export function taskPlanFor(outcome: SetupResult): readonly TaskPlanStep[] {
  const plan = outcome.id.startsWith("application:")
    ? applicationPlan(outcome.id.slice("application:".length))
    : Object.hasOwn(plans, outcome.id) ? plans[outcome.id] : undefined;
  if (!plan) throw new Error(`No task plan is defined for setup result: ${outcome.id}`);
  return plan;
}
