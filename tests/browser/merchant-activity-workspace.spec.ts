import {closeDatabase} from "../../src/platform/database/client";
import {signInPerson} from "./helpers/prepaid";
import {expect,test} from "@playwright/test";
import {merchantDashboardProjectionSchema} from "../../src/modules/acquiring/dashboard-contracts";
import {merchantAccessFixture} from "../helpers/merchant-access";
import {terminalCheckoutFixture,payTerminal} from "../helpers/terminal-checkout";

test.afterAll(closeDatabase);
test("owner can manage every flat terminal while a terminal user sees only assigned work",async({page})=>{
 const {merchant,master,unit,operator}=await merchantAccessFixture();
 await signInPerson(page,merchant.personId);
 await page.goto(`/merchant-services?section=merchants&view=merchant:${merchant.serviceId}`);
 await expect(page.getByRole("heading",{name:"Payments for your business",exact:true})).toBeVisible();
 await expect(page.getByRole("heading",{name:unit.displayName,exact:true})).toBeVisible();
 await expect(page.getByRole("article").getByRole("heading",{name:master.displayName,exact:true})).toBeVisible();
 await expect(page.getByRole("button",{name:"Add payment terminal",exact:true})).toBeVisible();
 const tools=page.getByRole("navigation",{name:`Tools for ${unit.displayName}`,exact:true});
 await tools.getByRole("link",{name:"Payments",exact:true}).click();
 await expect(page.getByRole("heading",{name:unit.displayName,exact:true})).toBeVisible();
 await page.getByRole("navigation",{name:"Payment terminal navigation"}).getByRole("link",{name:"Overview",exact:true}).click();
 await expect(page).toHaveURL(/\/merchant-services/);
 await signInPerson(page,operator.personId);
 await page.goto("/merchant-services?section=merchants");
 await expect(page.getByRole("heading",{name:"Payments you collect",exact:true})).toBeVisible();
 await expect(page.getByRole("heading",{name:unit.displayName,exact:true})).toBeVisible();
 await expect(page.getByRole("article").getByRole("heading",{name:master.displayName,exact:true})).toHaveCount(0);
 await expect(page.getByRole("button",{name:"Add payment terminal",exact:true})).toHaveCount(0);
 await expect(page.getByRole("link",{name:"Payment balance",exact:true})).toHaveCount(0);
 await expect(page.getByRole("navigation",{name:`Tools for ${unit.displayName}`,exact:true}).getByRole("link",{name:"People",exact:true})).toHaveCount(0);
 const dashboard=await page.request.get("/api/v1/merchants/dashboard");expect(dashboard.status()).toBe(200);
 const data=merchantDashboardProjectionSchema.parse(await dashboard.json());
 expect(data.units.map(row=>row.id)).toEqual([unit.id]);expect(data.moneyAccounts).toEqual([]);
 expect((await page.request.get(`/api/v1/merchants/${master.id}/operations`)).status()).toBe(404);
});

test("merchant activity keeps exact terminal scope, dates, pages and receipts while money stays current",async({page})=>{
 test.setTimeout(180_000);const f=await terminalCheckoutFixture("50000");
 for(let i=0;i<26;i++)await payTerminal(f);
 await signInPerson(page,f.merchant.personId);
 const today=new Date().toISOString().slice(0,10),query=new URLSearchParams({view:`merchant:${f.merchant.serviceId}`,period:"custom",from:today,to:today,q:f.channel.description,status:"COLLECTED",activity:"payments"});
 await page.goto(`/merchant-services?${query}`);
 await expect(page.getByRole("heading",{name:"Payments for your business",exact:true})).toBeVisible();
 await expect(page.getByRole("combobox",{name:"Show",exact:true})).toHaveValue(`merchant:${f.merchant.serviceId}`);
 await expect(page.getByRole("searchbox",{name:"Find a payment",exact:true})).toHaveValue(f.channel.description);
 const table=page.getByRole("table");await expect(table.locator("tbody tr")).toHaveCount(25);
 await page.getByRole("link",{name:"Next",exact:true}).click();await expect(table.locator("tbody tr")).toHaveCount(1);
 await page.reload();expect(new URL(page.url()).searchParams.get("page")).toBe("2");
 const data=await page.request.get(`/api/v1/merchants/dashboard?${query}&page=2`);expect(data.status()).toBe(200);
 const selected=merchantDashboardProjectionSchema.parse(await data.json()).activity.rows[0]!;
 await table.getByRole("link",{name:f.channel.description,exact:true}).click();
 const detail=page.getByRole("dialog",{name:"Payment details",exact:true});await expect(detail).toContainText(selected.reference);
 await page.reload();await expect(detail).toContainText(selected.reference);
 await expect(detail.getByRole("link",{name:"Get help with this payment",exact:true})).toHaveAttribute("href",new RegExp(`payment=${selected.paymentId}`));
 const returnTo=new URL(page.url()).searchParams.get("returnTo");expect(returnTo).not.toBeNull();
 await detail.getByRole("link",{name:"View payment request",exact:true}).click();
 const channelDetails=page.getByRole("dialog",{name:"Payment request details",exact:true});await expect(channelDetails).toBeVisible();
 expect(new URL(page.url()).searchParams.get("returnTo")).toBe(returnTo);
 await expect(channelDetails.getByRole("link",{name:"Preview payment page",exact:true})).toHaveAttribute("href",f.publication.publicHref);
 await channelDetails.getByRole("button",{name:"Close details",exact:true}).click();
 await page.getByRole("navigation",{name:"Payment terminal navigation"}).getByRole("link",{name:"Overview",exact:true}).click();
 await expect(page).toHaveURL(url=>url.pathname==="/merchant-services"&&[...query].every(([key,value])=>url.searchParams.get(key)===value)&&url.searchParams.get("page")==="2");
 const csv=await page.request.get((await page.getByRole("link",{name:"Download activity",exact:true}).getAttribute("href"))!);
 expect(csv.status()).toBe(200);expect(csv.headers()["cache-control"]).toContain("no-store");expect((await csv.text()).split("\r\n")).toHaveLength(28);
 await page.getByRole("navigation",{name:"Payment overview views"}).getByRole("link",{name:"Payment balance",exact:true}).click();
 await expect(page.locator(".md-money-grid>div").filter({has:page.getByText("Payments ready to move",{exact:true})})).toContainText("$325.00");
 await page.getByRole("navigation",{name:"Payment overview views"}).getByRole("link",{name:"Overview",exact:true}).click();
 await page.getByRole("searchbox",{name:"Find a payment",exact:true}).fill("No matching order");
 await page.getByRole("button",{name:"Search",exact:true}).click();await expect(page.getByRole("heading",{name:"No payments to show",exact:true})).toBeVisible();
 await page.getByRole("combobox",{name:"When",exact:true}).selectOption("last7");
 await page.getByRole("button",{name:"Search",exact:true}).click();
 await expect(page.getByRole("searchbox",{name:"Find a payment",exact:true})).toHaveValue("No matching order");
});
